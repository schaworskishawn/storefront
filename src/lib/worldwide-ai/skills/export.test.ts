import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { ROLE_BY_ID } from "../agents/registry";
import { FOUNDATIONS, ROLE_PACKS, SKILLS } from "./catalog";
import { hashOfSkill, manifestOf, renderSkillMarkdown, type SkillDefinition } from "./types";

/**
 * The portable copies of the skills, under skills/worldwide-ai/. They are an export of the catalog for runtimes that read
 * skill folders, never a second source: this test fails when a file differs from what the catalog renders, and
 * `pnpm worldwide-ai:skills` rewrites them.
 */

const ROOT = join(process.cwd(), "skills", "worldwide-ai");
const unix = (text: string) => text.replace(/\r\n/g, "\n");

const manifestText = (skill: SkillDefinition) =>
	`${JSON.stringify({ ...manifestOf(skill), sha256: hashOfSkill(skill) }, null, "\t")}\n`;

function readme(): string {
	const row = (skill: SkillDefinition) =>
		`| [\`${skill.id}\`](${skill.id}/SKILL.md) | ${skill.title} | ${skill.version} | ${
			skill.kind === "role-pack"
				? ROLE_BY_ID[skill.agents[0]].name
				: `${skill.agents.length} agent${skill.agents.length === 1 ? "" : "s"}`
		} |`;
	return [
		"# Worldwide AI skills",
		"",
		"<!-- Generated by `pnpm worldwide-ai:skills` from src/lib/worldwide-ai/skills. Do not edit by hand: a test fails when these files and the catalog differ. -->",
		"",
		`${SKILLS.length} written procedures for the Worldwide AI agents: ${FOUNDATIONS.length} shared foundations and one role pack for each of the ${ROLE_PACKS.length} agents. Each folder holds a \`SKILL.md\` in the Agent Skills format and a \`manifest.json\` with what the application binds it to and the checksum of its exact content.`,
		"",
		"These files are an export. The source is `src/lib/worldwide-ai/skills/`, and what guides an agent's work is never a file here: it is the version a person approved in the workspace, stored exactly as approved. A skill explains how work is done. It grants no tool, permission or authority.",
		"",
		"See `docs/worldwide-ai.md` for how skills are evaluated, approved, revoked and rolled back.",
		"",
		"## Shared foundations",
		"",
		"| Skill | Title | Version | Used by |",
		"| --- | --- | --- | --- |",
		...FOUNDATIONS.map(row),
		"",
		"## Role packs",
		"",
		"| Skill | Title | Version | Agent |",
		"| --- | --- | --- | --- |",
		...ROLE_PACKS.map(row),
		"",
	].join("\n");
}

const expected = (): Map<string, string> =>
	new Map<string, string>([
		["README.md", readme()],
		...SKILLS.flatMap(
			(skill): Array<[string, string]> => [
				[`${skill.id}/SKILL.md`, renderSkillMarkdown(skill)],
				[`${skill.id}/manifest.json`, manifestText(skill)],
			],
		),
	]);

describe("the exported skill packages", () => {
	it("match the catalog file for file (run `pnpm worldwide-ai:skills` after changing a skill)", () => {
		const files = expected();
		if (process.env.WORLDWIDE_AI_WRITE_DOCS === "1") {
			for (const [path, text] of files) {
				mkdirSync(dirname(join(ROOT, path)), { recursive: true });
				writeFileSync(join(ROOT, path), text, "utf8");
			}
			// A skill that was renamed or removed leaves no folder behind.
			for (const entry of readdirSync(ROOT))
				if (statSync(join(ROOT, entry)).isDirectory() && !SKILLS.some((skill) => skill.id === entry))
					rmSync(join(ROOT, entry), { recursive: true, force: true });
		}
		expect(existsSync(ROOT), "skills/worldwide-ai is missing").toBe(true);
		const different = [...files].filter(
			([path, text]) =>
				!existsSync(join(ROOT, path)) || unix(readFileSync(join(ROOT, path), "utf8")) !== text,
		);
		expect(different.map(([path]) => path)).toEqual([]);
		const folders = readdirSync(ROOT).filter((entry) => statSync(join(ROOT, entry)).isDirectory());
		expect(folders.sort()).toEqual(SKILLS.map((skill) => skill.id).sort());
	});

	it("are in the portable format: a folder named for the skill, with a name and a description up front", () => {
		for (const skill of SKILLS) {
			const text = renderSkillMarkdown(skill);
			const [, name, description] = /^---\nname: (.+)\ndescription: "(.+)"\n---\n/.exec(text) ?? [];
			expect(name, skill.id).toBe(skill.id);
			expect(name).toMatch(/^[a-z0-9]+(-[a-z0-9]+)*$/);
			expect(name.length).toBeLessThanOrEqual(64);
			expect(description.length).toBeGreaterThan(40);
			expect(description.length).toBeLessThanOrEqual(1024);
			// Nothing application-specific is invented in the frontmatter: bindings live in manifest.json.
			expect(text.split("\n---\n")[0].split("\n")).toHaveLength(3);
			expect(JSON.parse(manifestText(skill))).toMatchObject({ id: skill.id, sha256: hashOfSkill(skill) });
		}
	});
});
